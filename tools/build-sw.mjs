// Generates sw.js with a precache list of the app shell: node tools/build-sw.mjs
// Run after changing files so installed apps pick up the new version.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
});
const rel = (f) => relative(root, f).replace(/\\/g, '/');
const shell = ['index.html', 'styles.css', 'manifest.webmanifest',
  ...[...walk(join(root, 'src')), ...walk(join(root, 'vendor')).filter((f) => f.endsWith('.js')), ...walk(join(root, 'icons'))].map(rel)];
const hash = createHash('sha1');
for (const f of [...shell, ...walk(join(root, 'assets')).map(rel)]) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest('hex').slice(0, 10);

const sw = `// Generated by tools/build-sw.mjs — do not edit by hand.
const VERSION = '${version}';
const SHELL = 'spur-shell-' + VERSION;
const RUNTIME = 'spur-runtime-' + VERSION;
const PRECACHE = ${JSON.stringify(['./', ...shell], null, 0)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => !k.endsWith(VERSION)).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
// cache-first for app files and horse meshes, stale-while-revalidate for fonts
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === location.origin) {
    e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(RUNTIME).then((c) => c.put(req, copy)); }
      return res;
    })));
  } else if (url.host.includes('fonts.googleapis.com') || url.host.includes('fonts.gstatic.com')) {
    e.respondWith(caches.open(RUNTIME).then((c) => c.match(req).then((hit) => {
      const net = fetch(req).then((res) => { c.put(req, res.clone()); return res; }).catch(() => hit);
      return hit || net;
    })));
  }
});
`;
writeFileSync(join(root, 'sw.js'), sw);
console.log(`sw.js written: version ${version}, ${shell.length} precached files`);

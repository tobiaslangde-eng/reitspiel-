// Generates src/player/rider-data.js (base64 mesh data) from the signed-distance definitions.
//   node src/player/gen/build-rider.js          full quality
//   node src/player/gen/build-rider.js fast     coarse preview, a few seconds
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { argv } from 'node:process';
import { Buffer } from 'node:buffer';
import { prepare, makeField, evalPrim } from './sdf.js';
import { meshField } from './mesher.js';
import { bodyPrims, BODY_BOUNDS, headPrims, HEAD_BOUNDS, handPrims, HAND_BOUNDS } from './bodydef.js';
import { BONE_INDEX } from '../skeleton.js';

const OUT = fileURLToPath(new URL('../rider-data.js', import.meta.url));
const FAST = argv.includes('fast');
const CELL = { body: 0.011, head: 0.004, hand: 0.0032 };
const NECK_CUT = 0.56; // the body mesh ends inside the head mesh's neck

// per-vertex ambient occlusion, skin weights
function finish(mesh, F0, prepared, { tau = 0.045, aoScale = 2.4, aoStep = 0.02 } = {}) {
  const { verts, normals } = mesh;
  const n = verts.length;
  const ao = new Uint8Array(n);
  const skinIndex = new Uint8Array(n * 4);
  const skinWeight = new Uint8Array(n * 4);
  const adds = prepared.filter((p) => p.type !== 'sub');
  const dist = new Float32Array(adds.length);
  for (let v = 0; v < n; v++) {
    const p = verts[v], nn = normals[v];
    let occ = 0, w = 1;
    for (let s = 1; s <= 6; s++) {
      const h = aoStep * s;
      occ += (h - F0(p[0] + nn[0] * h, p[1] + nn[1] * h, p[2] + nn[2] * h)) * w;
      w *= 0.6;
    }
    ao[v] = Math.round(Math.max(0, Math.min(1, 1 - occ * aoScale)) * 255);

    let dmin = 1e9;
    for (let i = 0; i < adds.length; i++) { dist[i] = evalPrim(adds[i], p[0], p[1], p[2]); if (dist[i] < dmin) dmin = dist[i]; }
    const wb = new Map();
    for (let i = 0; i < adds.length; i++) {
      const f = 1 - (dist[i] - dmin) / tau;
      if (f <= 0) continue;
      const bi = BONE_INDEX[adds[i].bone];
      wb.set(bi, Math.max(wb.get(bi) || 0, f * f));
    }
    const top = [...wb.entries()].sort((a, b) => b[1] - a[1]).slice(0, 4);
    const sum = top.reduce((a, b) => a + b[1], 0);
    const q = top.map(([, wt]) => Math.round((wt / sum) * 255));
    q[0] += 255 - q.reduce((a, b) => a + b, 0); // exact sum, the largest weight absorbs rounding
    top.forEach(([bi], k) => { skinIndex[v * 4 + k] = bi; skinWeight[v * 4 + k] = q[k]; });
  }
  return { ao, skinIndex, skinWeight };
}

const POS_SCALE = 8000;
function encode(mesh, extra, meta) {
  const n = mesh.verts.length;
  const big = n > 65535;
  const metaBuf = Buffer.from(JSON.stringify(meta));
  const header = new Uint32Array([0x31534d52, n, mesh.tris.length, metaBuf.length, big ? 1 : 0]);
  const pos = new Int16Array(n * 3), nor = new Int8Array(n * 3);
  mesh.verts.forEach((p, i) => { for (let a = 0; a < 3; a++) pos[i * 3 + a] = Math.round(p[a] * POS_SCALE); });
  mesh.normals.forEach((p, i) => { for (let a = 0; a < 3; a++) nor[i * 3 + a] = Math.round(p[a] * 127); });
  const ind = big ? new Uint32Array(mesh.tris) : new Uint16Array(mesh.tris);
  return Buffer.concat([
    Buffer.from(header.buffer), metaBuf, Buffer.from(pos.buffer), Buffer.from(nor.buffer), Buffer.from(extra.ao),
    Buffer.from(extra.skinIndex), Buffer.from(extra.skinWeight), Buffer.from(ind.buffer),
  ]);
}

function build(name, prims, bounds, cell, clip, opts = {}) {
  const t0 = Date.now();
  const prepared = prepare(prims);
  const joinK = { 1: 0.05, 2: 0.05, 3: 0.014, 4: 0.014 };
  const F0 = makeField(prepared, null, joinK);
  const F = clip ? makeField(prepared, clip, joinK) : F0;
  const mesh = meshField(F, { min: bounds.min, max: bounds.max, cell, smooth: opts.smooth ?? 2 });
  const extra = finish(mesh, F0, prepared, opts);
  const buf = encode(mesh, extra, { scale: POS_SCALE, cell });
  console.log(`${name}: ${mesh.verts.length} verts, ${mesh.tris.length / 3} tris, ${buf.length} bytes, ${mesh.evals} evals, ${Date.now() - t0} ms`);
  return buf.toString('base64');
}

const f = FAST ? 2 : 1;
const only = argv.find((a) => a.startsWith('only='))?.slice(5).split(',');
const want = (n) => !only || only.includes(n);
let old = {};
if (only) old = await import(OUT).catch(() => ({}));
const out = { ...old };
if (want('body')) out.BODY = build('body', bodyPrims(), BODY_BOUNDS, CELL.body * f, (x, y, z, d) => Math.max(d, y - NECK_CUT, -0.93 - y));
if (want('head')) out.HEAD = build('head', headPrims(), HEAD_BOUNDS, CELL.head * f, (x, y, z, d) => Math.max(d, 0.44 - y), { tau: 0.03, aoStep: 0.012, aoScale: 3 });
if (want('hand')) out.HAND = build('hand', handPrims(), HAND_BOUNDS, CELL.hand * f, null, { tau: 0.012, aoStep: 0.006, aoScale: 4 });

const src = `// Generated by src/player/gen/build-rider.js — do not edit by hand.\n${Object.entries(out).map(([k, v]) => `export const ${k} = '${v}';`).join('\n')}\n`;
writeFileSync(OUT, src);
console.log('wrote', OUT, (src.length / 1024).toFixed(0) + ' KB');
